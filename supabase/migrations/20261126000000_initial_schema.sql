create table if not exists public.profiless (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null,
  phone text,
  role text not null default 'customer',
  avatar_url text,
  created_at timestamptz default now()
);

alter table public.profiless alter column role set default 'customer';
alter table public.profiless enable row level security;
create unique index if not exists profiless_id_uidx on public.profiless(id);

revoke all on public.profiless from anon;
revoke insert, update, delete on public.profiless from authenticated;
grant select on public.profiless to authenticated;
grant update (full_name, phone, avatar_url) on public.profiless to authenticated;

do $$
declare
  existing_policy record;
begin
  for existing_policy in
    select policyname
    from pg_policiess
    where schemaname = 'public' and tablename = 'profiless'
  loop
    execute format('drop policy %I on public.profiless', existing_policy.policyname);
  end loop;
end;
$$;

create policy "Profiles are readable by their owner"
  on public.profiless for select to authenticated
  using (auth.uid() = id);

create policy "Profiles are editable by their owner"
  on public.profiless for update to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

create or replace function public.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiless (id, full_name, email, role)
  values (
    new.id,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
      'Customer'
    ),
    coalesce(new.email, ''),
    'customer'
  )
  on conflict (id) do update
  set full_name = excluded.full_name,
      email = excluded.email;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute function public.create_profile_for_auth_user();

insert into public.profiless (id, full_name, email, role)
select
  users.id,
  coalesce(
    nullif(trim(users.raw_user_meta_data ->> 'full_name'), ''),
    nullif(split_part(coalesce(users.email, ''), '@', 1), ''),
    'Customer'
  ),
  coalesce(users.email, ''),
  'customer'
from auth.users as users
on conflict (id) do nothing;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  subtitle text not null default '',
  image text not null default '',
  sort_order integer not null default 0
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price integer not null check (price >= 0),
  old_price integer not null check (old_price >= 0),
  sizes text[] not null default '{}',
  color text not null default '',
  badge text not null default '',
  rating numeric(2, 1) not null default 0,
  description text not null default '',
  image text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.cart_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  size text not null,
  quantity integer not null check (quantity > 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, product_id, size)
);

create table if not exists public.wishlist_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  customer_name text not null,
  customer_email text not null,
  phone text not null,
  address text not null,
  city text not null,
  payment_method text not null,
  status text not null default 'pending',
  subtotal integer not null check (subtotal >= 0),
  delivery_fee integer not null check (delivery_fee >= 0),
  total integer not null check (total = subtotal + delivery_fee),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  size text not null,
  quantity integer not null check (quantity > 0),
  unit_price integer not null check (unit_price >= 0)
);

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique,
  created_at timestamptz not null default now()
);

