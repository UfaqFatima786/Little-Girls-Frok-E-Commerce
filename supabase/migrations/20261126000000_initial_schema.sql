create or replace function public.add_to_cart(
  p_product_id bigint,
  p_size text,
  p_quantity integer default 1
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_sizes text[];
begin
  if v_user_id is null then
    raise exception 'You must be signed in to add items to your cart.';
  end if;

  if p_quantity < 1 then
    raise exception 'Item quantity must be greater than zero.';
  end if;

  select sizes into v_sizes from public.products where id = p_product_id;
  if not found or not (p_size = any(v_sizes)) then
    raise exception 'The selected product size is not available.';
  end if;

  insert into public.cart_items (user_id, product_id, size, quantity, updated_at)
  values (v_user_id, p_product_id, p_size, p_quantity, now())
  on conflict (user_id, product_id, size)
  do update set
    quantity = public.cart_items.quantity + excluded.quantity,
    updated_at = now();
end;
$$;

create or replace function public.place_order(
  p_customer_name text,
  p_customer_email text,
  p_phone text,
  p_address text,
  p_city text,
  p_payment_method text,
  p_delivery_fee integer,
  p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_order_id uuid;
  v_item jsonb;
  v_product public.products%rowtype;
  v_size text;
  v_quantity integer;
  v_subtotal integer := 0;
begin
  if v_user_id is null then
    raise exception 'You must be signed in to place an order.';
  end if;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your cart is empty.';
  end if;

  if p_delivery_fee < 0 then
    raise exception 'Delivery fee cannot be negative.';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_size := v_item->>'size';
    v_quantity := (v_item->>'quantity')::integer;

    if v_quantity < 1 then
      raise exception 'Item quantity must be greater than zero.';
    end if;

    select * into v_product
    from public.products
    where id = (v_item->>'product_id')::bigint;

    if not found or not (v_size = any(v_product.sizes)) then
      raise exception 'A product or selected size is no longer available.';
    end if;

    v_subtotal := v_subtotal + (v_product.price * v_quantity);
  end loop;

  if p_delivery_fee <> case when v_subtotal >= 5000 then 0 else 200 end then
    raise exception 'Delivery fee does not match the order total.';
  end if;

  insert into public.orders (
    user_id, customer_name, customer_email, phone, address, city,
    payment_method, subtotal, delivery_fee, total
  ) values (
    v_user_id, p_customer_name, p_customer_email, p_phone, p_address, p_city,
    p_payment_method, v_subtotal, p_delivery_fee, v_subtotal + p_delivery_fee
  )
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_size := v_item->>'size';
    v_quantity := (v_item->>'quantity')::integer;

    select * into v_product
    from public.products
    where id = (v_item->>'product_id')::bigint;

    insert into public.order_items (
      order_id, product_id, product_name, size, quantity, unit_price
    ) values (
      v_order_id, v_product.id, v_product.name, v_size, v_quantity, v_product.price
    );
  end loop;

  delete from public.cart_items where user_id = v_user_id;

  return v_order_id;
end;
$$;

