create or replace function public.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiless (id, full_name, email, role)
  values (
    new.id,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
      'Customer'
    ),
    coalesce(new.email, ''),
    'customer'
  )
  on conflict (id) do update
  set full_name = excluded.full_name,
      email = excluded.email;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute function public.create_profile_for_auth_user();

insert into public.profiless (id, full_name, email, role)
select
  users.id,
  coalesce(
    nullif(trim(users.raw_user_meta_data ->> 'full_name'), ''),
    nullif(split_part(coalesce(users.email, ''), '@', 1), ''),
    'Customer'
  ),
  coalesce(users.email, ''),
  'customer'
from auth.users as users
on conflict (id) do nothing;

create or replace function public.add_to_cart(
  p_product_id uuid,
  p_quantity integer default 1
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_stock integer;
  v_is_active boolean;
  v_in_cart integer;
begin
  if v_user_id is null then
    raise exception 'You must be signed in to add items to your cart.';
  end if;

  if p_quantity < 1 then
    raise exception 'Item quantity must be greater than zero.';
  end if;

  select stock, is_active into v_stock, v_is_active
  from public.products
  where id = p_product_id
  for update;

  if not found or v_is_active is distinct from true then
    raise exception 'This product is no longer available.';
  end if;

  select coalesce(quantity, 0) into v_in_cart
  from public.cart_items
  where user_id = v_user_id and product_id = p_product_id;

  if v_in_cart + p_quantity > v_stock then
    raise exception 'Requested quantity is greater than available stock.';
  end if;

  insert into public.cart_items (user_id, product_id, quantity, updated_at)
  values (v_user_id, p_product_id, p_quantity, now())
  on conflict (user_id, product_id)
  do update set
    quantity = public.cart_items.quantity + excluded.quantity,
    updated_at = now();
end;
$$;

create or replace function public.place_order(
  p_full_name text,
  p_email text,
  p_phone text,
  p_address_line text,
  p_city text,
  p_state text default null,
  p_postal_code text default null,
  p_country text default 'Pakistan',
  p_notes text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_order_id uuid;
  v_subtotal numeric(10, 2) := 0;
  v_shipping_fee numeric(10, 2);
  v_item record;
  v_item_count integer := 0;
begin
  if v_user_id is null then
    raise exception 'You must be signed in to place an order.';
  end if;

  if nullif(trim(p_full_name), '') is null
    or nullif(trim(p_phone), '') is null
    or nullif(trim(p_address_line), '') is null
    or nullif(trim(p_city), '') is null then
    raise exception 'Name, phone, address, and city are required.';
  end if;

  for v_item in
    select cart.product_id, cart.quantity, product.price, product.stock,
           product.name, product.image_url, product.is_active
    from public.cart_items as cart
    join public.products as product on product.id = cart.product_id
    where cart.user_id = v_user_id
    for update of product
  loop
    if v_item.is_active is distinct from true then
      raise exception 'A product in your cart is no longer available.';
    end if;
    if v_item.quantity > v_item.stock then
      raise exception 'A product in your cart no longer has enough stock.';
    end if;

    v_item_count := v_item_count + 1;
    v_subtotal := v_subtotal + (v_item.price * v_item.quantity);
  end loop;

  if v_item_count = 0 then
    raise exception 'Your cart is empty.';
  end if;

  v_shipping_fee := case when v_subtotal >= 5000 then 0 else 200 end;

  insert into public.orders (
    user_id, full_name, email, phone, address_line, city, state, postal_code,
    country, subtotal, shipping_fee, total_amount, payment_method,
    payment_status, order_status, notes
  )
  values (
    v_user_id, trim(p_full_name), nullif(trim(p_email), ''), trim(p_phone),
    trim(p_address_line), trim(p_city), nullif(trim(p_state), ''),
    nullif(trim(p_postal_code), ''), coalesce(nullif(trim(p_country), ''), 'Pakistan'),
    v_subtotal, v_shipping_fee, v_subtotal + v_shipping_fee, 'COD',
    'pending', 'pending', nullif(trim(p_notes), '')
  )
  returning id into v_order_id;

  for v_item in
    select cart.product_id, cart.quantity, product.price, product.stock,
           product.name, product.image_url
    from public.cart_items as cart
    join public.products as product on product.id = cart.product_id
    where cart.user_id = v_user_id
    for update of product
  loop
    insert into public.order_items (
      order_id, product_id, product_name, product_image,
      unit_price, quantity, subtotal
    )
    values (
      v_order_id, v_item.product_id, v_item.name, v_item.image_url,
      v_item.price, v_item.quantity, v_item.price * v_item.quantity
    );

    update public.products
    set stock = stock - v_item.quantity,
        updated_at = now()
    where id = v_item.product_id;
  end loop;

  insert into public.addresses (
    user_id, full_name, phone, email, address_line, city,
    state, postal_code, country, is_default
  )
  select
    v_user_id, trim(p_full_name), trim(p_phone), nullif(trim(p_email), ''),
    trim(p_address_line), trim(p_city), nullif(trim(p_state), ''),
    nullif(trim(p_postal_code), ''), coalesce(nullif(trim(p_country), ''), 'Pakistan'),
    not exists (select 1 from public.addresses where user_id = v_user_id)
  where not exists (
    select 1 from public.addresses as address
    where address.user_id = v_user_id
      and address.phone = trim(p_phone)
      and address.address_line = trim(p_address_line)
      and address.city = trim(p_city)
  );

  delete from public.cart_items where user_id = v_user_id;
  return v_order_id;
end;
$$;

