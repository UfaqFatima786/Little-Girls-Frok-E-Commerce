drop policy if exists "Storefront reads active products" on public.products;
create policy "Storefront reads active products"
  on public.products for select to anon, authenticated
  using (is_active = true);

drop policy if exists "Users read their own profile" on public.profiless;
create policy "Users read their own profile"
  on public.profiless for select to authenticated
  using (auth.uid() = id);

drop policy if exists "Users update their own profile" on public.profiless;
create policy "Users update their own profile"
  on public.profiless for update to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

drop policy if exists "Users manage their own cart" on public.cart_items;
create policy "Users manage their own cart"
  on public.cart_items for all to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users manage their own wishlist" on public.wishlist;
create policy "Users manage their own wishlist"
  on public.wishlist for all to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users read their own orders" on public.orders;
create policy "Users read their own orders"
  on public.orders for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users read their own order items" on public.order_items;
create policy "Users read their own order items"
  on public.order_items for select to authenticated
  using (
    exists (
      select 1 from public.orders
      where orders.id = order_items.order_id
        and orders.user_id = auth.uid()
    )
  );

drop policy if exists "Users manage their own addresses" on public.addresses;
create policy "Users manage their own addresses"
  on public.addresses for all to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Anyone subscribes to the newsletter"
  on public.newsletter_subscribers;
create policy "Anyone subscribes to the newsletter"
  on public.newsletter_subscribers for insert to anon, authenticated
  with check (email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$');

